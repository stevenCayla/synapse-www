import { CASES } from '../data/cases';
import { FEATURES } from '../data/features';
import { POSTS } from '../data/posts';
import { ROLES } from '../data/roles';
import { LANGS, type Lang } from './index';

export type StaticKey =
  | 'home' | 'features' | 'integrations' | 'tour' | 'pricing' | 'security' | 'trust' | 'cases'
  | 'blog' | 'changelog' | 'soon' | 'status' | 'glossary' | 'about' | 'careers' | 'demo'
  | 'disclosure' | 'legal' | 'privacy';
export type DetailKey = 'feature' | 'role' | 'case' | 'post';
export type RouteKey = StaticKey | DetailKey;

export interface Entry {
  key: RouteKey;
  id?: string;
  slug: Record<Lang, string>;
}

// Slugs follow URLS.md: French without prefix, English under /en/.
const STATIC: Record<StaticKey, [string, string]> = {
  home: ['', ''],
  features: ['fonctionnalites', 'features'],
  integrations: ['integrations', 'integrations'],
  tour: ['visite-guidee', 'product-tour'],
  pricing: ['tarifs', 'pricing'],
  security: ['securite', 'security'],
  trust: ['confiance', 'trust'],
  cases: ['etudes-de-cas', 'case-studies'],
  blog: ['blog', 'blog'],
  changelog: ['nouveautes', 'changelog'],
  soon: ['feuille-de-route', 'roadmap'],
  status: ['statut', 'status'],
  glossary: ['glossaire', 'glossary'],
  about: ['a-propos', 'about'],
  careers: ['carrieres', 'careers'],
  demo: ['demo', 'demo'],
  disclosure: ['divulgation-responsable', 'responsible-disclosure'],
  legal: ['mentions-legales', 'legal'],
  privacy: ['confidentialite', 'privacy'],
};

const sec = (key: StaticKey): Record<Lang, string> => ({ fr: STATIC[key][0], en: STATIC[key][1] });
const under = (key: StaticKey, s: Record<Lang, string>): Record<Lang, string> => ({
  fr: `${STATIC[key][0]}/${s.fr}`,
  en: `${STATIC[key][1]}/${s.en}`,
});

export const ENTRIES: Entry[] = [
  ...(Object.keys(STATIC) as StaticKey[]).map((key): Entry => ({ key, slug: sec(key) })),
  ...FEATURES.map((f): Entry => ({ key: 'feature', id: f.k, slug: under('features', f.s) })),
  ...ROLES.map((r): Entry => ({ key: 'role', id: r.k, slug: { fr: `solutions/${r.s.fr}`, en: `solutions/${r.s.en}` } })),
  ...CASES.map((c): Entry => ({ key: 'case', id: c.k, slug: under('cases', c.s) })),
  ...POSTS.map((p): Entry => ({ key: 'post', id: p.id, slug: { fr: `blog/${p.id}`, en: `blog/${p.id}` } })),
];

/** Absolute path of a page, with a leading slash and no trailing slash (except the home pages). */
export function path(key: RouteKey, lang: Lang, id?: string): string {
  const e = ENTRIES.find((x) => x.key === key && (x.id ?? '') === (id ?? ''));
  if (!e) throw new Error(`Unknown route ${key}${id ? `:${id}` : ''}`);
  const prefix = lang === 'en' ? '/en' : '';
  // The English home is /en (no trailing slash, like every other page); the French home is /.
  return e.slug[lang] ? `${prefix}/${e.slug[lang]}` : prefix || '/';
}

/** Entries that are generated by the catch-all route (the two home pages have their own files). */
export const GENERATED = ENTRIES.filter((e) => e.key !== 'home');

export const rolePath = (lang: Lang, id: string) => path('role', lang, id);
export const featurePath = (lang: Lang, id: string) => path('feature', lang, id);
export const casePath = (lang: Lang, id: string) => path('case', lang, id);
export const postPath = (lang: Lang, id: string) => path('post', lang, id);

/** Find the entry of an absolute pathname (used for hreflang alternates in the sitemap). */
export function entryOf(pathname: string): { entry: Entry; lang: Lang } | undefined {
  const clean = pathname.replace(/\/+$/, '') || '/';
  for (const entry of ENTRIES) {
    for (const lang of LANGS) {
      const p = path(entry.key, lang, entry.id).replace(/\/+$/, '') || '/';
      if (p === clean) return { entry, lang };
    }
  }
  return undefined;
}
